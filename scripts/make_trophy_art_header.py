"""Generate 3ds/include/amun/3ds/trophy_art.hpp from the Studio 16 px metal trophies.

The plugin has no filesystem image loader, so the unlock badge (docs/metal-tiers.md)
embeds the art as 0xAARRGGBB words, one 16x16 table per tier in MetalTier order
(Copper..Rhodium). Run after `scripts/make_metal_tiers.py`; tests fail if the committed
header is stale.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from compiler.metal_tiers import MetalTier  # noqa: E402

SIZE = 16
SOURCE = ROOT / "studio" / "assets" / "metal-tiers"
DEFAULT_OUT = ROOT / "3ds" / "include" / "amun" / "3ds" / "trophy_art.hpp"


def render() -> str:
    lines = [
        "#pragma once",
        "",
        "// GENERATED by scripts/make_trophy_art_header.py from studio/assets/metal-tiers/*-16.png.",
        "// Do not edit by hand. 0xAARRGGBB, alpha is 0 (transparent) or 255 (opaque).",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace amun::threeds {",
        "",
        f"inline constexpr std::size_t kTrophyArtSize = {SIZE}U;",
        "",
        "// Index = MetalTier - 1 (Copper, Bronze, Silver, Electrum, Gold, Platinum, Rhodium).",
        f"inline constexpr std::uint32_t kTrophyArt[7][{SIZE * SIZE}] = {{",
    ]
    for tier in MetalTier:
        if tier is MetalTier.NONE:
            continue
        image = Image.open(SOURCE / f"{tier.slug}-16.png").convert("RGBA")
        if image.size != (SIZE, SIZE):
            raise SystemExit(f"{tier.slug}-16.png must be {SIZE}x{SIZE}, got {image.size}")
        words = []
        for y in range(SIZE):
            for x in range(SIZE):
                r, g, b, a = image.getpixel((x, y))
                if a not in (0, 255):
                    raise SystemExit(f"{tier.slug}-16.png has partial alpha at {x},{y}")
                words.append(f"0x{a:02X}{r:02X}{g:02X}{b:02X}U" if a else "0U")
        lines.append(f"    {{ // {tier.slug}")
        for row in range(SIZE):
            lines.append("        " + ", ".join(words[row * SIZE:(row + 1) * SIZE]) + ",")
        lines.append("    },")
    lines += ["};", "", "} // namespace amun::threeds", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    args.out.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
